# tests/rhosocial/activerecord_oracle_test/feature/backend/dialect/test_auto_increment_ddl.py
"""Regression tests for DDL compilation of auto-increment, standard types,
boolean defaults, and timestamps.

Covers bugs found in rbac cross-backend testing:
- is_auto_increment=True on PRIMARY_KEY must produce GENERATED BY DEFAULT
  AS IDENTITY (Oracle 12+).
- format_create_table_statement must return a string for all types.
- BooleanType with DEFAULT True must be accepted.
- TimestampType must map to TIMestamp.

The boolean default is version-dependent and is asserted on both sides rather
than only the side that works: a 23ai dialect has the ``BOOLEAN`` type and the
``TRUE`` / ``FALSE`` keywords, so the column is spelled with them; a pre-23ai
dialect has neither, so the DEFAULT is *refused* with a message naming the
``NUMBER(1)`` convention, rather than emitted as a keyword the parser rejects.
Both directions are pinned, because a case that only ever exercises the working
side cannot notice the refusal going away.
"""

import pytest

from rhosocial.activerecord.backend.expression import (
    CreateTableStatement, ColumnDefinition, ColumnConstraint,
    ColumnDefaultConstraint, ColumnNotNullConstraint, ColumnPrimaryKeyConstraint,
)
from rhosocial.activerecord.backend.expression.types import (
    BooleanType, IntegerType, TextType, TimestampType, VarCharType,
)
from rhosocial.activerecord.backend.expression.objects import Table
from rhosocial.activerecord.backend.dialect.exceptions import UnsupportedFeatureError
from rhosocial.activerecord.backend.impl.oracle.dialect import OracleDialect


@pytest.fixture
def dialect():
    """The baseline this file was written against: 19c.

    Auto-increment (12+), the standard types and timestamps are all expressible
    here, so those cases do not need anything newer.
    """
    return OracleDialect(version=(19, 0, 0))


@pytest.fixture
def dialect_with_boolean():
    """A dialect where ``DEFAULT TRUE`` is SQL at all: 23ai.

    Oracle spells ``TRUE`` / ``FALSE`` as keywords from 23ai only. Before that
    the words are not in the grammar -- ``BOOLEAN`` itself is ``ORA-00902`` on
    21c -- so a ``DEFAULT TRUE`` column cannot be written on the baseline
    dialect, and the backend refuses it with a message naming the pre-23ai
    ``NUMBER(1)`` convention instead of emitting a keyword the parser rejects.
    A case that asserts a boolean default *compiles* is therefore a 23ai case,
    and it is given the dialect that has it rather than the baseline.
    """
    return OracleDialect(version=(23, 0, 0))


def _pk(dialect):
    return [ColumnConstraint(
        dialect,
        branch=ColumnPrimaryKeyConstraint(dialect, is_auto_increment=True),
    )]


def _build_table(dialect):
    return CreateTableStatement(
        dialect=dialect, table=Table(dialect, "test_tbl"),
        columns=[
            ColumnDefinition(dialect, "id", IntegerType(dialect), constraints=_pk(dialect)),
            ColumnDefinition(dialect, "name", TextType(dialect),
                constraints=[ColumnConstraint(dialect, branch=ColumnNotNullConstraint(dialect))]),
            ColumnDefinition(dialect, "flag", BooleanType(dialect),
                constraints=[ColumnConstraint(dialect, branch=ColumnNotNullConstraint(dialect)),
                             ColumnConstraint(dialect, branch=ColumnDefaultConstraint(dialect, True))]),
            ColumnDefinition(dialect, "code", VarCharType(length=16, dialect=dialect)),
            ColumnDefinition(dialect, "created_at", TimestampType(dialect=dialect)),
        ],
    )


class TestAutoIncrementDDL:

    def test_auto_increment_in_ddl(self, dialect_with_boolean):
        sql, _ = _build_table(dialect_with_boolean).to_sql()
        assert "GENERATED BY DEFAULT AS IDENTITY" in sql.upper(), \
            f"auto-increment missing: {sql}"

    def test_all_standard_types_compile(self, dialect_with_boolean):
        sql, params = _build_table(dialect_with_boolean).to_sql()
        assert isinstance(sql, str)
        assert isinstance(params, tuple)

    def test_boolean_default_true(self, dialect_with_boolean):
        d = dialect_with_boolean
        expr = CreateTableStatement(
            dialect=d, table=Table(d, "bool_test"),
            columns=[
                ColumnDefinition(d, "id", IntegerType(d), constraints=_pk(d)),
                ColumnDefinition(d, "flag", BooleanType(d),
                    constraints=[ColumnConstraint(d, branch=ColumnNotNullConstraint(d)),
                                 ColumnConstraint(d, branch=ColumnDefaultConstraint(d, True))]),
            ],
        )
        sql, _ = expr.to_sql()
        assert sql
        # The whole point of the case: on 23ai Oracle has a real BOOLEAN type
        # and the keyword, so the column is spelled with them both rather than
        # being mapped down to NUMBER(1) the way an older dialect maps it.
        assert "BOOLEAN" in sql.upper()
        assert "DEFAULT TRUE" in sql.upper()

    def test_timestamp_type(self, dialect):
        expr = CreateTableStatement(
            dialect=dialect, table=Table(dialect, "ts_test"),
            columns=[
                ColumnDefinition(dialect, "id", IntegerType(dialect), constraints=_pk(dialect)),
                ColumnDefinition(dialect, "created_at", TimestampType(dialect=dialect)),
            ],
        )
        sql, _ = expr.to_sql()
        assert "TIMESTAMP" in sql.upper()

    def test_boolean_default_is_refused_below_23ai(self, dialect):
        """A boolean default is a refusal, not a mis-spelled keyword.

        The other half of the case above, and the half that keeps the refusal
        honest. Oracle's pre-23ai SQL has no ``TRUE`` / ``FALSE`` words, so a
        backend that emitted ``DEFAULT TRUE`` on this dialect would be writing
        text the parser rejects. The backend refuses instead, and names both
        the reason and the pre-23ai ``NUMBER(1)`` convention the caller can use
        -- so a reader hitting the error knows what to write rather than only
        what went wrong.

        Without this, the 23ai case above would pass by the backend having
        quietly learned to spell ``TRUE`` everywhere, and nothing would say the
        refusal was ever checked.
        """
        expr = CreateTableStatement(
            dialect=dialect, table=Table(dialect, "bool_test"),
            columns=[
                ColumnDefinition(dialect, "id", IntegerType(dialect), constraints=_pk(dialect)),
                ColumnDefinition(dialect, "flag", BooleanType(dialect),
                    constraints=[
                        ColumnConstraint(dialect, branch=ColumnNotNullConstraint(dialect)),
                        ColumnConstraint(
                            dialect, branch=ColumnDefaultConstraint(dialect, True)
                        ),
                    ]),
            ],
        )
        with pytest.raises(UnsupportedFeatureError) as exc_info:
            expr.to_sql()
        message = str(exc_info.value)
        assert "TRUE literal in a DDL position" in message, message
        assert "23ai" in message, message
        assert "NUMBER(1)" in message, message
