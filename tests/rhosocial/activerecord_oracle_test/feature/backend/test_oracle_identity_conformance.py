# tests/rhosocial/activerecord_oracle_test/feature/backend/test_oracle_identity_conformance.py
"""Oracle identity-column conformance: declaration, renderer, and execution.

Oracle accepts the SQL-standard ``GENERATED ... AS IDENTITY`` clause from 12c
on and declares every option the clause carries. The formatter stays core's --
Oracle does not override ``format_identity_clause``, so the gating keeps living
in one place. Oracle's grammar differs only in spelling, so the three
``identity_*_keyword`` hooks are overridden instead: ``NOCYCLE`` / ``NOORDER``
/ ``NOCACHE``, each measured on live 18c / 21c / 23c. Core's spaced
``NO CYCLE`` / ``NO ORDER`` / ``NO CACHE`` are refused by every measured
server (ORA-02000), and ``CACHE 0`` is refused too (ORA-04010), which is why
the falsy cache count spells ``NOCACHE``.

The column-definition order is Oracle's grammar: ``col type
[VISIBLE|INVISIBLE] [GENERATED ... AS IDENTITY [(options)]] [inline_constraint
...]``. The previous constraints-first order rendered ``PRIMARY KEY GENERATED
...`` and ``... AS IDENTITY INVISIBLE``, both refused on every measured server
(ORA-00907 on 18c / 21c, ORA-03076 on 23c).

Rendering is not execution. The unit tests below pin the declaration and the
rendered bytes; the execution tests then send the rendered ``CREATE TABLE`` to
live 18c / 21c / 23c. Every live verdict runs sentinels first on the same
connection -- ``THIS IS NOT SQL`` must be REJECTED and ``SELECT 1 FROM DUAL``
must be ACCEPTED -- because an ``ACCEPTED`` that has never been contrasted with
a rejection is not evidence.

The legacy ``is_auto_increment`` constraint path routes through the gated
formatter: Oracle 12+ renders the same identity clause as before, while Oracle
< 12 refuses by name instead of silently dropping the clause. The live servers
are all 12+, so the below-12 refusal is a dialect-level test and the live case
covers 12+.
"""

