-- tests/rhosocial/activerecord_oracle_test/feature/backend/adapters/native/schema/native_types.sql
--
-- Native-type carriers for the Oracle backend tests.  Each table holds one
-- family; the columns are the types this backend has an adapter for.  The
-- statements are read by ``native_support.ensure_tables`` (one ``-- table:``
-- marker per statement, terminated by ``;``).
--
-- Deliberately absent:
--   * BFILE        -- needs a DIRECTORY object and a read strategy (3b gap)
--   * OBJECT/REF/VARRAY/NESTED TABLE -- need a dict carrier design (3b gap)
--   * SDO_GEOMETRY -- created only by the spatial tests, because the Oracle
--                     Free image may not ship the Spatial component (this
--                     container does not: CREATE TABLE ... SDO_GEOMETRY
--                     raises ORA-00902).

-- table: native_numeric
CREATE TABLE native_numeric (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    dec_val NUMBER(10, 2),
    plain_val NUMBER,
    bfloat_val BINARY_FLOAT,
    bdouble_val BINARY_DOUBLE
);

-- table: native_temporal
CREATE TABLE native_temporal (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    date_val DATE,
    ts_val TIMESTAMP(6),
    tstz_val TIMESTAMP(6) WITH TIME ZONE,
    tsltz_val TIMESTAMP(6) WITH LOCAL TIME ZONE,
    ytm_val INTERVAL YEAR(2) TO MONTH,
    dts_val INTERVAL DAY(2) TO SECOND(6)
);

-- table: native_anchor
CREATE TABLE native_anchor (
    id NUMBER PRIMARY KEY
);

-- table: native_identifiers
CREATE TABLE native_identifiers (
    id NUMBER PRIMARY KEY,
    rid ROWID,
    urid UROWID
);

-- table: native_xml_json
CREATE TABLE native_xml_json (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    xml_val XMLTYPE,
    json_val JSON
);

-- table: native_boolean_vector
CREATE TABLE native_boolean_vector (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    flag BOOLEAN,
    emb VECTOR(3, FLOAT32)
);

-- table: native_raw_bits
CREATE TABLE native_raw_bits (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    raw_bits RAW(8)
);
